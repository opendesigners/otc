// Parses /content and writes src/generated/content.json (+ a typed module).
// Pages, the assistant prompt and the keyword fallback all read that JSON.
//
// Drafts (publish: false) are included only with --drafts (used by `pnpm dev`)
// or OTCF_SHOW_DRAFTS=true; otherwise they never reach the bundle at all.
//
// Usage: pnpm content:build [--drafts]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { ContentBundle } from "../src/content/schema.ts";
import { loadAllContent, loadPhotos } from "./lib/content.ts";
import { loadLocalEnv } from "./lib/env.ts";

const OUT_DIR = path.resolve(import.meta.dirname, "../src/generated");

const TYPED_MODULE = `// Generated by scripts/build-content.ts — do not edit.
import type { ContentBundle } from "../content/schema";
import data from "./content.json";

export const bundle = data as ContentBundle;
`;

// Display order everywhere communities are listed (GDG Ilorin first, at the
// user's request, 2026-11-07); anything new goes after.
const COMMUNITY_ORDER = ["gdg-ilorin", "open-designers", "open-devs"];

export function buildContent({ drafts }: { drafts: boolean }): ContentBundle {
  const all = loadAllContent();
  const visible = drafts ? all : all.filter((doc) => doc.publish);
  const rank = (slug: string) => (COMMUNITY_ORDER.indexOf(slug) + 1 || 99);
  const bundle: ContentBundle = {
    includesDrafts: drafts,
    docs: visible,
    communities: all
      .filter((doc) => doc.kind === "community")
      .sort((a, b) => rank(a.slug) - rank(b.slug))
      .map(({ slug, title, tagline, route }) => ({
        slug,
        title,
        tagline,
        route: visible.some((d) => d.route === route) ? route : undefined,
      })),
    photos: loadPhotos(),
  };
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, "content.json"), `${JSON.stringify(bundle, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT_DIR, "content.ts"), TYPED_MODULE);
  return bundle;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  loadLocalEnv();
  const drafts = process.argv.includes("--drafts") || process.env.OTCF_SHOW_DRAFTS === "true";
  try {
    const bundle = buildContent({ drafts });
    const hidden = drafts ? "drafts included" : "drafts excluded";
    console.log(`✓ content.json: ${bundle.docs.length} docs (${hidden})`);
  } catch (error) {
    console.error(`✗ ${(error as Error).message}`);
    process.exit(1);
  }
}
